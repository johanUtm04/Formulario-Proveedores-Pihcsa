                <li><strong>- Cancelación:</strong> Solicitar la supresión de sus datos personales de los archivos, registros o bases de datos de PIHCSA, cuando considere que no están siendo tratados conforme a los principios legales.</li>
                <li><strong>- Oposición:</strong> Oponerse al tratamiento de sus datos personales para fines específicos.</li>
