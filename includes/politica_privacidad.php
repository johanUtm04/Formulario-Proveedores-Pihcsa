<p><strong>VIII. MEDIDAS DE SEGURIDAD</strong><br>
PIHCSA implementa medidas de seguridad administrativas, técnicas y físicas suficientes para proteger los datos personales contra daño, pérdida, alteración, destrucción, uso, acceso o tratamiento no autorizado, conforme a los principios de seguridad y confidencialidad establecidos en la ley.</p>


<p><strong>IX. TIEMPO DE CONSERVACIÓN DE LOS DATOS PERSONALES</strong><br>
PIHCSA conservará los datos personales del titular únicamente durante el tiempo que resulte necesario y proporcional para cumplir con las finalidades para las cuales fueron recabados, así como para dar cumplimiento a obligaciones legales, contractuales, fiscales y administrativas derivadas de la relación jurídica existente.<br>
En términos generales, los datos personales serán conservados conforme a los siguientes criterios:</p>

<ul>
    <li><strong>Datos comerciales y contractuales:</strong> durante la vigencia de la relación jurídica y hasta por cinco (5) años posteriores a su terminación, para efectos de atención de responsabilidades legales o reclamaciones, siendo posible ampliar dicho termino antes mencionado, por causas legales que así lo requieran.</li>
    <li><strong>Datos fiscales y contables:</strong> por el plazo que determinen las disposiciones fiscales aplicables.</li>
    <li><strong>Datos utilizados para finalidades secundarias:</strong> hasta en tanto el titular revoque su consentimiento.</li>
    <li><strong>Evidencia fotográfica:</strong> será conservada por un período de tres (3) años. En caso de que la relación jurídica se mantenga vigente una vez transcurrido dicho plazo, será necesaria la actualización de la evidencia correspondiente.</li>
</ul>

<p>Una vez cumplidos los plazos de conservación, los datos personales serán bloqueados y posteriormente cancelados, o bien, eliminados o anonimizados, de conformidad con los artículos 11, 25 y demás aplicables de la LFPDPPP y su Reglamento.</p>

